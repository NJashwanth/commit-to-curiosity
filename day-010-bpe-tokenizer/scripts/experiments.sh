#!/usr/bin/env bash
# Train vocabs of 512, 1024 and 4096 tokens with and without pre-tokenization,
# then write results/stats.md and results/viz.md.
#
# Usage: ./scripts/experiments.sh   (runs ./scripts/fetch-data.sh first if needed)
set -euo pipefail
cd "$(dirname "$0")/.."

[ -s data/shakespeare.txt ] || ./scripts/fetch-data.sh
cargo build --release --quiet
bpe=./target/release/bpe
mkdir -p vocabs results

# Held-out split: first 90% of lines to train, last 10% to measure.
total=$(wc -l < data/shakespeare.txt)
cut=$((total * 9 / 10))
head -n "$cut" data/shakespeare.txt > data/train90.txt
tail -n +"$((cut + 1))" data/shakespeare.txt > data/test10.txt

field() { grep "^$2" "$1" | cut -c16- | awk '{print $1}'; }
used() { grep "^vocab used" "$1" | cut -c16- | sed -E 's/.*\((.*)\)/\1/'; }

stats=results/stats.md
{
  echo "# Stats"
  echo
  echo "Generated by \`scripts/experiments.sh\` on $(date +%Y-%m-%d) ($(uname -m))."
  echo "In-sample: trained on all of tinyshakespeare ($(wc -c < data/shakespeare.txt | tr -d ' ') bytes) and measured on the same text."
  echo "Held-out: trained on the first 90% of lines, measured on the last 10%."
  echo "\`split\` is GPT-4 pre-tokenization (the default); \`no-split\` is \`--no-split\`. Every vocab includes \`<|endoftext|>\`."
  echo
  echo "| vocab | mode | tokens | bytes/token | held-out bytes/token | vocab used | encode MB/s |"
  echo "|------:|------|-------:|------------:|---------------------:|-----------:|------------:|"
} > "$stats"

details=$(mktemp)
for n in 512 1024 4096; do
  for mode in split no-split; do
    flag=""
    if [ "$mode" = no-split ]; then flag="--no-split"; fi
    v="vocabs/v$n-$mode.json"
    h="vocabs/heldout-$n-$mode.json"
    "$bpe" train --input data/shakespeare.txt --vocab-size "$n" --out "$v" --quiet $flag > /dev/null
    "$bpe" train --input data/train90.txt --vocab-size "$n" --out "$h" --quiet $flag > /dev/null
    s=$(mktemp)
    ho=$(mktemp)
    "$bpe" stats --vocab "$v" --input data/shakespeare.txt > "$s"
    "$bpe" stats --vocab "$h" --input data/test10.txt --top 0 > "$ho"
    echo "| $n | $mode | $(field "$s" tokens) | $(field "$s" bytes/token) | $(field "$ho" bytes/token) | $(used "$s") | $(field "$s" 'encode speed') |" >> "$stats"
    { echo; echo "## $n tokens, $mode"; echo; echo '```'; cat "$s"; echo '```'; } >> "$details"
    rm -f "$s" "$ho"
  done
done
cat "$details" >> "$stats"
rm -f "$details"

viz=results/viz.md
lines=("To be, or not to be, that is the question:" "Hello 👋 నమస్తే world")
{
  echo "# Viz"
  echo
  echo "\`bpe viz --no-color\` output. In a terminal each token gets its own background colour instead of brackets."
  for n in 512 1024 4096; do
    for mode in split no-split; do
      echo
      echo "## $n tokens, $mode"
      for line in "${lines[@]}"; do
        echo
        echo '```'
        "$bpe" viz --vocab "vocabs/v$n-$mode.json" --no-color "$line"
        echo '```'
      done
    done
  done
} > "$viz"

echo "wrote $stats and $viz"
